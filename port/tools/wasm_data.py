#!/usr/bin/env python3
"""The game's data tables for the WebAssembly build, from their shapes in port/data (make_skeleton.py).

The native builds assemble port/data/*.s (GNU as, x86) and make_dat.py then reads the linker's map to write the
list of where each table's values come from on the user's disc. wasm-ld has no such map format, so here:

  port/build/gen_wasm/data/<table>.s   one wasm data section per table file (so a file's tables stay contiguous,
                                       in order, as natively), each label with its size, 16-byte alignment, plus a
                                       start label __bt3tab_<table> for the list below;
  port/build/gen_wasm/data_list.c      the same records make_dat.py writes to <program>.dat (address in the program,
                                       source file, offset in it, length; and the checksum of port/data/index.txt),
                                       as C data whose addresses the linker fills in (`table start + offset`).

Directives: .space N (values from the disc: zero here, listed) and .zero N -> .skip N; .long sym[+k] -> .int32;
.long D_3BE71C -> the address 0x3BE71C (the native link defines that symbol with --defsym).
A .long that names a function is declared with a placeholder .functype: wasm-ld puts the defined function's own
table slot there whatever the declared type
(checked 2026-10-11 with two objects, both link orders: the call through the table reaches the real function). No game value is written by this
tool: the output holds shapes and disc offsets only.

Usage: python port/tools/wasm_data.py <object folder>...   (the objects tell which named symbols are functions)"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "port/data"
OUT = ROOT / "port/build/gen_wasm"
ABSOLUTE = {"D_3BE71C": 0x3BE71C}  # link.py: -Wl,--defsym=D_3BE71C=0x3BE71C

def functions(folders):
    """Names that are functions: defined as such in the objects, or named like the decompilation's functions."""
    objs = [str(p) for f in folders for p in sorted(pathlib.Path(f).glob("*.o"))]
    out = set()
    for i in range(0, len(objs), 200):
        r = subprocess.run(["llvm-nm", "--defined-only"] + objs[i:i + 200], capture_output=True, text=True)
        out |= {l.split()[-1] for l in r.stdout.splitlines() if re.match(r"^[0-9a-f]+ [Tt] ", l)}
    return out

def convert(src, funcs, labels):
    """Returns (wasm assembly, table start label, [(offset, length)] of the .space runs, size in bytes)."""
    name = src.stem  # e.g. cod_1C3380.data
    start = "__bt3tab_" + re.sub(r"\W", "_", name)
    kind = "bss" if any(l.strip() == ".section .bss" for l in src.read_text().splitlines()) else "data"
    body, sizes, runs, decl, off = [], {}, [], set(), 0
    cur = [start]
    for line in src.read_text().splitlines():
        p = line.split()
        if not p or p[0].startswith("#") or p[0] in (".section", ".p2align", ".globl"):
            continue
        if p[0].endswith(":"):
            lab = p[0][:-1]
            body.append(("label", lab))
            cur.append(lab)
            sizes[lab] = off
        elif p[0] in (".space", ".zero"):
            n = int(p[1])
            if p[0] == ".space":
                runs.append((off, n))
            body.append(("skip", n))
            off += n
        elif p[0] == ".long":
            m = re.fullmatch(r"(\w+)(?:\+(\d+))?", p[1])
            if not m:
                raise SystemExit(f"{src.name}: cannot read {line.strip()}")
            sym, add = m.group(1), int(m.group(2) or 0)
            if sym in ABSOLUTE:
                body.append(("int", str(ABSOLUTE[sym] + add)))
            else:
                if sym not in labels and (sym in funcs or not sym.startswith("D_")):
                    decl.add(sym)
                body.append(("int", sym + (f"+{add}" if add else "")))
            off += 4
        else:
            raise SystemExit(f"{src.name}: unknown directive {line.strip()}")
    # each label's size: to the next label at a higher offset, or to the end
    offs = sorted(set(sizes.values()) | {off})
    size_of = {lab: next((o for o in offs if o > at), off) - at for lab, at in sizes.items()}
    out = [f"# {name}: generated by port/tools/wasm_data.py from port/data/{src.name} (shape only)"]
    out += [f".functype {f} () -> ()" for f in sorted(decl)]
    out += [f'.section .{kind}.bt3_{re.sub(r"[^0-9A-Za-z_]", "_", name)},"",@', ".p2align 4",
            f".globl {start}", f".hidden {start}", f".type {start},@object", f"{start}:"]
    for what, v in body:
        if what == "label":
            out += [f".globl {v}", f".type {v},@object", f".size {v}, {size_of[v]}", f"{v}:"]
        elif what == "skip":
            out.append(f"    .skip {v}")
        else:
            if kind == "bss":
                raise SystemExit(f"{src.name}: an address in a .bss table")
            out.append(f"    .int32 {v}")
    out.append(f".size {start}, {off}")
    return "\n".join(out) + "\n", start, runs, off

def main():
    folders = sys.argv[1:] or [str(ROOT / "port/build/obj_wasm")]
    funcs = functions(folders)
    files = sorted(SRC.glob("*.s"), key=lambda f: f.stem)  # make_dat.py's order: sorted table names
    labels = {l.split()[0][:-1] for f in files for l in f.read_text().splitlines() if re.match(r"^\w+:", l)}
    index, checksum = {}, None
    for l in (SRC / "index.txt").read_text().splitlines():
        p = l.split()
        if len(p) == 3 and not l.startswith("#"):
            index[p[0]] = (int(p[1]), int(p[2], 16))
        elif len(p) == 2 and p[0] == "checksum":
            checksum = int(p[1], 16)
    if checksum is None:
        raise SystemExit("port/data/index.txt has no checksum")
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    records, externs, nbytes = [], [], 0
    for f in files:
        text, start, runs, size = convert(f, funcs, labels)
        (OUT / "data" / f.name).write_text(text, newline="\n")
        name = f.stem
        if runs:
            if name not in index:
                raise SystemExit(f"{name}: has values from the disc but no line in port/data/index.txt")
            which, so = index[name]
            externs.append(start)
            records += [(start, o, which, so + o, n) for o, n in runs]
            nbytes += sum(n for _, n in runs)
    # make_dat.py writes the records in the order of sorted(table names): the checksum is over the bytes in that order
    c = ["/* generated by port/tools/wasm_data.py: where the values of the game's data tables come from on the user's",
         "   disc (the list make_dat.py writes to <program>.dat for the native builds). Offsets only, no game data. */",
         "#include <stdint.h>"]
    c += [f"extern char {s}[];" for s in sorted(set(externs))]
    c += ["typedef struct { void *addr; uint32_t source, offset, length; } PortDataRun;",
          f"const uint32_t gPortDataRunCount = {len(records)};",
          f"const uint64_t gPortDataChecksum = 0x{checksum:016X}ull;",
          "const PortDataRun gPortDataRuns[] = {"]
    c += [f"    {{{s} + {o}, {w}, 0x{so:X}, {n}}}," for s, o, w, so, n in records]
    c += ["};"]
    (OUT / "data_list.c").write_text("\n".join(c) + "\n", newline="\n")
    print(f"{len(files)} tables converted; {len(records)} runs, {nbytes} bytes to fetch from the disc at start; "
          f"{sum(1 for f in files for l in f.read_text().splitlines() if l.strip().startswith('.long'))} addresses")

if __name__ == "__main__":
    main()
